#!/usr/bin/env python3
"""sunfont-gas.py SUNFONT_S OUT_S -- AMIX's console font source for GNU as.

The ZZ9000/Z3660 RTG driver's text console draws with the console's
builtinfont[] (usr/sys/amiga/console/sunfont.s: the 25x12 Sun font).  A
stock kernel does not carry it, so relink-040-zz9000*.sh link it in
(SUNFONT_O).  An AMIX tree has sunfont.o only where someone assembled it on
AMIX; the public usr/sys (amigaux/amix-system) has the source alone, written
for AMIX's as and m4.  This runs m4 over it in its own directory (it
includes screen.i) and rewrites the result for the m68k-cbm-sysv4 GNU as:
'#' comments dropped, ';' statements one per line, text/global/set/long/
short/byte as .text/.globl/.set/.long/.short/.byte.  Nothing of the source
is kept in this tree; the output is made at build time from the user's or
the public usr/sys.  Assembled, its .text equals the sunfont.o AMIX's own
as makes (.text and relocations compared, 2026-11-17).
"""
import os
import re
import subprocess
import sys

DIRECTIVES = {"text": ".text", "data": ".data", "global": ".globl", "set": ".set",
              "long": ".long", "short": ".short", "byte": ".byte", "even": ".even"}


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__.strip())
    src, out = sys.argv[1], sys.argv[2]
    m4 = next((m for m in ("m4", "gm4") if subprocess.run(
        ["sh", "-c", "command -v " + m], capture_output=True).returncode == 0), None)
    if not m4:
        sys.exit("sunfont-gas: no m4 on PATH")
    text = subprocess.run([m4, os.path.basename(src)], cwd=os.path.dirname(os.path.abspath(src)),
                          capture_output=True, text=True, check=True).stdout
    lines = []
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].rstrip()
        for stmt in line.split(";"):
            stmt = stmt.strip()
            if not stmt:
                continue
            m = re.match(r"^([A-Za-z_][A-Za-z0-9_]*):\s*(.*)$", stmt)
            if m:
                lines.append(m.group(1) + ":")
                stmt = m.group(2).strip()
                if not stmt:
                    continue
            parts = re.split(r"\s+", stmt, maxsplit=1)
            word, rest = parts[0], parts[1] if len(parts) > 1 else ""
            if word not in DIRECTIVES:
                sys.exit("sunfont-gas: unexpected statement: %r" % stmt)
            lines.append("\t%s\t%s" % (DIRECTIVES[word], rest.replace(" ", "")))
    if not any(l == "builtinfont:" for l in lines):
        sys.exit("sunfont-gas: no builtinfont in %s" % src)
    with open(out, "w") as f:
        f.write("| generated by sunfont-gas.py from %s\n" % os.path.basename(src))
        f.write("\n".join(lines) + "\n")


main()
