#!/usr/bin/env python3
"""gen.py OUTDIR -- the plain GL calls of zzgl.h's ZZGL_SIMPLE list as C:
zzgl_gen_enc.h (the 060's functions: one command each), zzgl_gen_dec.h (core
1's cases) and zzgl_gen_names.h (name -> function for GetProcAddress)."""
import os, re, sys

H = os.path.dirname(os.path.abspath(__file__))
# decoded by hand in zzgl_dec.c (state kept there)
DEC_BY_HAND = {"ClientActiveTextureARB"}
TYPES = {"e": "GLenum", "i": "GLint", "u": "GLuint", "z": "GLsizei", "b": "GLboolean",
         "x": "GLbitfield", "c": "GLubyte", "f": "GLfloat", "d": "GLdouble"}


def calls():
    text = open(os.path.join(H, "zzgl.h")).read()
    block = text[text.index("#define ZZGL_SIMPLE(X)"):]
    block = block[:block.index("\n\n")]
    return re.findall(r'X\((\w+), "(\w*)"\)', block)


def main():
    out = sys.argv[1]
    enc, dec, names = [], [], []
    for name, sig in calls():
        params = ", ".join("%s a%d" % (TYPES[t], k) for k, t in enumerate(sig)) or "void"
        words = sum(2 if t == "d" else 1 for t in sig)
        body, w = [], 0
        args = []
        for k, t in enumerate(sig):
            if t == "f":
                body.append("p[%d] = bef(a%d);" % (w, k))
                args.append("F(%d)" % w)
                w += 1
            elif t == "d":
                body.append("put_double(p + %d, a%d);" % (w, k))
                args.append("D(%d)" % w)
                w += 2
            else:
                body.append("p[%d] = be32((uint32_t)a%d);" % (w, k))
                args.append("(%s)W(%d)" % (TYPES[t], w))
                w += 1
        enc.append("static void GLAPIENTRY\nzzgl_%s(%s)\n{\n   uint32_t *p = cmd(ZZ_%s, %d);\n\n   %s\n}\n"
                   % (name, params, name, words * 4, "\n   ".join(body) if body else "(void)p;"))
        if name not in DEC_BY_HAND:
            dec.append("   case ZZ_%s: gl%s(%s); break;" % (name, name, ", ".join(args)))
        names.append('   { "gl%s", (void *)zzgl_%s },' % (name, name))
    open(os.path.join(out, "zzgl_gen_enc.h"), "w").write(
        "/* zzgl_gen_enc.h -- generated by gen.py from zzgl.h */\n\n" + "\n".join(enc))
    open(os.path.join(out, "zzgl_gen_dec.h"), "w").write(
        "/* zzgl_gen_dec.h -- generated by gen.py from zzgl.h */\n" + "\n".join(dec) + "\n")
    open(os.path.join(out, "zzgl_gen_names.h"), "w").write(
        "/* zzgl_gen_names.h -- generated by gen.py from zzgl.h */\n" + "\n".join(names) + "\n")


main()
